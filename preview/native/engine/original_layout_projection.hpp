// All original indices remain identity-mapped. The only optional engine-only
// slot is the actual pure-v2 parser's final virtual padding entry. Call only
// after binding this fresh torrent_info to the exact original raw info/hashes.
struct OriginalLayoutProjection {
  std::size_t originalFiles=0, engineFiles=0;
  std::int64_t originalBytes=0, engineBytes=0, pieceLength=0;
  std::optional<std::size_t> trailingPad;
};
inline std::expected<OriginalLayoutProjection,storage::Error> projectOriginalLayout(
    const compat::OriginalLayout& original,const libtorrent::torrent_info& metadata) {
  using storage::Error;using storage::ErrorCode;
  const auto refused=[](const char* why)->std::expected<OriginalLayoutProjection,Error>{return std::unexpected(Error{ErrorCode::Unsupported,why});};
  const auto& files=metadata.files();
  if(original.files.empty()||original.files.size()>100000||metadata.num_files()<=0||metadata.num_files()>100000
      ||original.bytes<=0||original.pieceLength<=0||original.pieceLength!=metadata.piece_length()) {
    return refused("Invalid bounded original/engine geometry");
  }
  const auto count=static_cast<std::size_t>(metadata.num_files());
  if(count<original.files.size()||count-original.files.size()>1) return refused("Original/engine file count differs");
  std::int64_t end=0;
  for(std::size_t i=0;i<original.files.size();++i) {
    const auto& file=original.files[i];const auto index=libtorrent::file_index_t{static_cast<int>(i)};
    if(file.offset!=end||file.bytes<0||file.bytes>std::numeric_limits<std::int64_t>::max()-end
        ||file.bytes!=files.file_size(index)||file.offset!=files.file_offset(index)||file.padding!=files.pad_file_at(index)) {
      return refused("Original/engine file indices differ");
    }
    if(!file.padding&&std::filesystem::path(files.file_path(index))!=(original.multifile
        ?std::filesystem::path(original.name)/file.path:std::filesystem::path(file.path))) {
      return refused("Original/engine filename codecs differ");
    }
    end+=file.bytes;
  }
  if(end!=original.bytes) return refused("Original layout does not cover its declared byte span");
  const auto pieces=original.bytes/original.pieceLength+(original.bytes%original.pieceLength!=0);
  if(pieces<=0||pieces!=metadata.num_pieces()) return refused("Original/engine piece count differs");
  OriginalLayoutProjection projection{original.files.size(),count,original.bytes,metadata.total_size(),original.pieceLength,{}};
  if(count==original.files.size()) {
    if(original.bytes!=metadata.total_size()) return refused("Original/engine total bytes differ");
    return projection;
  }
  // The actual v2 parser rejects declared pad-file tree entries. Its only
  // additional slot is generated by file_storage::add_file_impl after a final
  // nonaligned file. v1/hybrid, reordered slots, real empties and extra pads do
  // not receive this exception.
  const auto hashes=metadata.info_hashes();const auto remainder=original.bytes%original.pieceLength;
  const auto tail=libtorrent::file_index_t{static_cast<int>(original.files.size())};
  if(hashes.has_v1()||!hashes.has_v2()||remainder==0||original.files.back().padding
      ||original.files.back().bytes==0) return refused("Only a pure-v2 synthetic final pad may extend the original layout");
  const auto pad=original.pieceLength-remainder;
  if(pad>std::numeric_limits<std::int64_t>::max()-original.bytes||!files.pad_file_at(tail)
      ||files.file_offset(tail)!=original.bytes||files.file_size(tail)!=pad
      ||metadata.total_size()!=original.bytes+pad) return refused("Engine-only trailing pad has an unexpected range");
  projection.trailingPad=original.files.size();return projection;
}

// Counts only intersections of ACTUALLY verified pieces with original logical
// bytes, including original pads, excluding the engine-only tail. No guessed
// subtraction from partially downloaded/unverified LT total_done is permitted.
inline std::expected<std::int64_t,storage::Error> verifiedOriginalBytes(
    std::int64_t bytes,std::int64_t pieceLength,std::span<const std::uint8_t> verified) {
  if(bytes<=0||pieceLength<=0||static_cast<std::uint64_t>(bytes/pieceLength+(bytes%pieceLength!=0))!=verified.size()
      ||std::ranges::any_of(verified,[](auto bit){return bit>1;})) {
    return std::unexpected(storage::Error{storage::ErrorCode::InvalidFormat,"Invalid actual original verified-piece projection"});
  }
  std::int64_t result=0;
  for(std::size_t i=0;i<verified.size();++i) {
    if(verified[i]) {
      const auto start=static_cast<std::int64_t>(i)*pieceLength;
      result+=std::min(pieceLength,bytes-start);
    }
  }
  return result;
}

