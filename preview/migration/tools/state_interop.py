#!/usr/bin/env python3
"""Qualify native gzip/plain state documents against the guarded Java oracle."""

import argparse
import contextlib
import gzip
import pathlib
import subprocess
import tempfile

from oracle import JAVA, verify_classes
from peer_interop import jvm
from sources import ROOT, save, sha256


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--driver", type=pathlib.Path, required=True)
    parser.add_argument("--classes", type=pathlib.Path, default=pathlib.Path("/tmp/biglybtc-oracle/classes"))
    parser.add_argument("--work", type=pathlib.Path)
    parser.add_argument("--output", type=pathlib.Path)
    args = parser.parse_args()
    oracle = verify_classes(args.classes)
    with contextlib.ExitStack() as stack:
        if args.work:
            args.work.mkdir(parents=True, exist_ok=False)
            work = args.work
        else:
            work = pathlib.Path(stack.enter_context(tempfile.TemporaryDirectory(prefix="biglybtc-state-interop-")))
        classes = work / "classes"
        classes.mkdir()
        harnesses = [ROOT / "migration/fixtures/java" / name for name in
            ("ReferenceFence.java", "InteropOracle.java", "GzipOracle.java")]

        def run(command, timeout=60):
            result = subprocess.run(list(map(str, command)), cwd=work, capture_output=True, timeout=timeout)
            if result.returncode:
                raise RuntimeError(result.stdout.decode(errors="replace") + result.stderr.decode(errors="replace"))
            return result.stdout.decode(errors="replace")

        run([JAVA / "javac", "-J-XX:ActiveProcessorCount=2", "--release", "8", "-cp", args.classes,
            "-d", classes, *harnesses])
        java = jvm(work, str(classes) + ":" + str(args.classes))
        run([*java, "InteropOracle", "generate", work / "fixtures"])
        profile = work / "fixtures/profile"
        run([*java, "GzipOracle", "compress", profile, work / "compressed"])
        output = work / "native"
        output.mkdir()
        checks = []
        for path in sorted((work / "compressed").iterdir()):
            target = output / path.name
            run([args.driver, "roundtrip", path, target], 30)
            if path.read_bytes() != target.read_bytes():
                raise ValueError("Unchanged gzip bytes differ")
            checks.append("byte-identical Java gzip " + path.name)
        edited = output / "edited.config.gz"
        run([args.driver, "set-port", work / "compressed/biglybt.config.gz", edited], 30)
        plain_before = (profile / "biglybt.config").read_bytes()
        if gzip.decompress(edited.read_bytes()) != plain_before.replace(b"i51413e", b"i51414e"):
            raise ValueError("Unknown decoded configuration bytes changed")
        state_to_verify = None
        # These retained profiles are generated by the guarded full-engine test,
        # never discovered from a user's installation or normal profile path.
        operational = ROOT / "migration/evidence/P00-04/java-native-v1.json"
        if operational.exists():
            import json
            reference = json.loads(operational.read_text())
            fixture_work = pathlib.Path(reference["java_log"]).parent
            if not str(fixture_work).startswith("/tmp/biglybtc-peer-"):
                raise ValueError("Operational reference must be our generated fixture")
            for index, name in enumerate(["downloads.config", "active/cache.dat", *[
                    name for name in reference["profile_files_sha256"] if name.startswith("active/")
                    and name.endswith(".dat") and name != "active/cache.dat"]]):
                path = fixture_work / "java/profile" / name
                if not path.exists():
                    continue
                before = path.read_bytes()
                if sha256(before) != reference["profile_files_sha256"][name]:
                    raise ValueError("Generated operational reference changed")
                target = output / ("operational-" + str(index))
                run([args.driver, "roundtrip", path, target], 30)
                if target.read_bytes() != before or path.read_bytes() != before:
                    raise ValueError("Operational state bytes changed")
                checks.append("byte-identical operational " + name)
                if name.startswith("active/") and name.endswith(".dat") and name != "active/cache.dat":
                    edited_state = output / "edited-state.dat"
                    run([args.driver, "invalidate-resume", path, edited_state], 30)
                    if before.count(b"5:validi1e") != 1 or edited_state.read_bytes() != before.replace(b"5:validi1e", b"5:validi0e", 1):
                        raise ValueError("Operational state edit changed more than its resume-valid marker")
                    state_to_verify = path
        verify = [*java, "GzipOracle", "verify", profile, output]
        if state_to_verify:
            verify.append(state_to_verify)
        verified = run(verify).strip()
        if state_to_verify and "PASS Java reads structured operational resume edit" not in verified:
            raise ValueError("Java did not verify the structured operational state edit")
        checks.append(verified)
        report = {"status": "passed", "source_commit": oracle["source_commit"],
            "core_class_digest": oracle["core_class_digest"], "driver_sha256": sha256(args.driver.read_bytes()),
            "harness_sha256": {p.name: sha256(p.read_bytes()) for p in harnesses}, "checks": checks,
            "limitations": ["Codec only; native session resume and compressed cache coherency remain pending",
                "Real operational profiles used only when the retained generated fixture exists"]}
        if args.output:
            save(args.output, report)
        for check in checks:
            print("PASS", check)


if __name__ == "__main__":
    main()
